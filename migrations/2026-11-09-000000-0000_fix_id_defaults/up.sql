-- doctors.id / materials.id had no default, so inserting a NewDoctor /
-- NewMaterial (which has no id) failed with a null id.
ALTER TABLE doctors ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('doctors', 'id'), COALESCE(MAX(id), 0) + 1, false) FROM doctors;

ALTER TABLE materials ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('materials', 'id'), COALESCE(MAX(id), 0) + 1, false) FROM materials;

-- Foreign-key columns were declared `serial`, so a missing value silently
-- took the next number from a counter instead of failing. They must always
-- be set explicitly.
ALTER TABLE studies ALTER COLUMN doctor_id DROP DEFAULT;
DROP SEQUENCE studies_doctor_id_seq;
ALTER TABLE studies ALTER COLUMN material_id DROP DEFAULT;
DROP SEQUENCE studies_material_id_seq;

ALTER TABLE citologias ALTER COLUMN study_id DROP DEFAULT;
DROP SEQUENCE citologias_study_id_seq;
ALTER TABLE histopatologias ALTER COLUMN study_id DROP DEFAULT;
DROP SEQUENCE histopatologias_study_id_seq;
